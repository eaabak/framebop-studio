// Bakes the temporary test art into transparent PNGs and writes the sizes
// and pivots the templates need. Run after changing parts.tsx or
// plates.tsx: FRAMEBOP_RENDER_BROWSER=<chrome> node test-art/bake.mjs
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { bundle } from "@remotion/bundler";
import { getCompositions, renderStill } from "@remotion/renderer";
import { format } from "prettier";

const here = (path) => fileURLToPath(new URL(path, import.meta.url));
const browserExecutable = process.env.FRAMEBOP_RENDER_BROWSER;
if (!browserExecutable) throw new Error("Set FRAMEBOP_RENDER_BROWSER.");

const outDir = await mkdtemp(join(tmpdir(), "framebop-art-"));
try {
  const serveUrl = await bundle({
    entryPoint: here("./root.tsx"),
    outDir,
    rootDir: here(".."),
    enableCaching: false,
  });
  const compositions = await getCompositions(serveUrl, { browserExecutable });
  for (const composition of compositions) {
    await renderStill({
      composition,
      serveUrl,
      output: here(`./png/${composition.id}.png`),
      imageFormat: "png",
      browserExecutable,
      overwrite: true,
    });
  }
  // Sizes and pivots, as plain data the templates import without React.
  const manifest = Object.fromEntries(
    compositions.map((c) => [
      c.id,
      {
        width: c.width,
        height: c.height,
        pivot: c.defaultProps.pivot,
        tip: c.defaultProps.tip,
      },
    ]),
  );
  const source = `// Generated by bake.mjs: sizes and pivots of the baked test art.\nexport const TEST_ART = ${JSON.stringify(manifest)} as const;\n`;
  await writeFile(
    here("./manifest.ts"),
    await format(source, { parser: "typescript" }),
  );
  console.log(`Baked ${compositions.length} pictures into test-art/png.`);
} finally {
  await rm(outDir, { recursive: true, force: true });
}
