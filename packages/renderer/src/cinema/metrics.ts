/** Kerning tightens set text by about this much against the summed widths. */
const KERNING = 0.985;

/** Width of `text` in pixels at `size` in Inter at `weight`. */
export function interWidth(text: string, size: number, weight = 850): number {
  const table = weight >= 825 ? W850 : W800;
  let units = 0;
  for (const ch of text) {
    const known = table[ch];
    if (known !== undefined) {
      units += known;
      continue;
    }
    const base = ch.normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    units += table[base] ?? table[base.toUpperCase()] ?? 700;
  }
  return (units / 1000) * size * KERNING;
}
